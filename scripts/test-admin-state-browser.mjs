import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { expressiveCodeConfig } from '../src/config/expressiveCodeConfig.ts';
const origin = process.env.BROWSER_BASE_URL || process.env.FEATURE_TEST_ORIGIN || 'http://127.0.0.1:4321';
const browser = await chromium.launch({ channel: 'chrome', headless: true });
try {
 const context = await browser.newContext({viewport:{width:1280,height:900}});
 const page = await context.newPage();
 const errors=[];
 page.on('pageerror', error => { errors.push(error.message); console.error(error.stack); });
 page.on('console', event => { if(event.type()==='error') console.error('Console:',event.text()); });
 const initialSidebar={enable:true,position:'both',leftComponents:[{type:'profile',enable:true,position:'top'}],rightComponents:[{type:'calendar',enable:true,position:'top'}],mobileBottomComponents:[]};
 const posts=[{file:'fixture.md',title:'隔离文章',published:'2026-01-01',draft:false,version:'p1',tags:[],description:''}];
 let sidebarVersion='v1'; let saved; let rejectSave=false; let loggedIn=true;
 await page.addInitScript(()=>sessionStorage.setItem('firefly-writing-auth','legacy-test-only'));
 const mockApi=async route=>{
  const req=route.request();const path=new URL(req.url()).pathname;
  if(path.endsWith('/session/'))return route.fulfill({status:loggedIn?200:401,json:loggedIn?{authenticated:true,mode:'deployed'}:{error:'登录已过期'}});
  if(path.endsWith('/logout/')){loggedIn=false;return route.fulfill({json:{ok:true}});}
  if(path.includes('/posts/'))return route.fulfill({json:{posts,mode:'deployed'}});
  if(path.includes('/content/sidebar/')){
   if(req.method()==='GET')return route.fulfill({json:{source:JSON.stringify(initialSidebar),version:sidebarVersion}});
   saved=req.postDataJSON();return route.fulfill(rejectSave?{status:409,json:{error:'版本冲突，请重新读取后合并'}}:{json:{ok:true,version:'v2',commit:{url:'https://example.test/commit/fixture'}}});
  }
  if(path.includes('/content/announcements/'))return route.fulfill({json:{source:JSON.stringify({title:'隔离公告',closable:false,items:[]}),version:'a1'}});
  return route.fulfill({json:{items:[],mode:'deployed'}});
 };
 await page.route('**/api/writing/**',mockApi);
 await page.goto(origin+'/admin/',{waitUntil:'domcontentloaded'});
 await page.waitForSelector('.admin-shell').catch(async error => { console.error(await page.locator('body').innerText()); throw error; });
 const indexedUrls=await page.evaluate(async()=>{
  const pagefind=await import('/pagefind/pagefind.js');
  const matches=await pagefind.search('适用范围');
  return Promise.all(matches.results.map(async result=>(await result.data()).url));
 });
 assert.ok(indexedUrls.length>0,'正向校验实际公共搜索索引');
 assert.ok(!indexedUrls.some(url=>/\/(admin|writing)\//.test(url)),'后台不能因共享隐私弹窗进入公共搜索');
 assert.equal(await page.locator('.admin-account-main').count(),1);
 assert.equal(await page.locator('.admin-theme-button').count(),1);
 await page.emulateMedia({colorScheme:'dark'});
 await page.waitForFunction(()=>document.documentElement.classList.contains('dark'));
 assert.equal(await page.evaluate(()=>document.documentElement.dataset.theme),expressiveCodeConfig.darkTheme,'主题同步配置中的代码主题');
 await page.emulateMedia({colorScheme:'light'});
 await page.waitForFunction(()=>!document.documentElement.classList.contains('dark'));
 assert.equal(await page.evaluate(()=>document.documentElement.dataset.theme),expressiveCodeConfig.lightTheme);
 await page.locator('.admin-sidebar nav button').filter({hasText:'文章管理'}).click();
 assert.equal(await page.locator('#admin-writing [title="退出登录"]:visible').count(),0,'后台退出入口只在左下账号菜单');
 await page.locator('.admin-sidebar nav button').filter({hasText:'站点管理'}).click();
 await page.locator('#admin-settings input[type=checkbox]').first().uncheck();
 sidebarVersion='external-v2';
 await page.getByRole('button',{name:'保存设置',exact:true}).click();
 await page.waitForFunction(()=>document.querySelector('.admin-toast')?.textContent?.includes('保存'));
 assert.equal(saved.version,'v1','必须提交开始编辑时读取的版本，不能先读新版再覆盖');
 assert.equal(JSON.parse(saved.source).leftComponents[0].enable,false);
 initialSidebar.leftComponents[0].enable=false;
 sidebarVersion='v2';
 await page.locator('.admin-sidebar nav button').filter({hasText:'笔记本'}).click();
 await page.getByRole('heading',{name:'笔记本',exact:true}).first().waitFor();
 await page.locator('#admin-records textarea').first().waitFor();
 await page.locator('.admin-sidebar nav button').filter({hasText:'站点管理'}).click();
 await page.locator('#admin-settings input[type=checkbox]').first().check();
 rejectSave=true;
 await page.getByRole('button',{name:'保存设置',exact:true}).click();
 await page.getByText(/版本冲突/).first().waitFor();
 assert.equal(await page.locator('#admin-settings input[type=checkbox]').first().isChecked(),true,'409应保留编辑');
 await page.reload({waitUntil:'domcontentloaded'});
 await page.waitForSelector('.admin-shell');
 assert.equal(await page.locator('#admin-settings input[type=checkbox]').first().isChecked(),true,'刷新应恢复本机未提交设置');
 await page.locator('.admin-sidebar nav button').filter({hasText:'公告管理'}).click();
 await page.getByLabel('公告栏标题',{exact:true}).fill('标签页 A 的修改');
 const second=await page.context().newPage();
 await second.route('**/api/writing/**',mockApi);
 await second.goto(origin+'/admin/',{waitUntil:'domcontentloaded'});
 await second.waitForSelector('.admin-shell');
 await second.locator('.admin-sidebar nav button').filter({hasText:'公告管理'}).click();
 await second.getByLabel('公告栏标题',{exact:true}).fill('标签页 B 的修改');
 await page.reload({waitUntil:'domcontentloaded'});
 await page.waitForSelector('.admin-shell');
 assert.equal(await page.getByLabel('公告栏标题',{exact:true}).inputValue(),'标签页 A 的修改','另一标签页不能覆盖本机暂存');
 await second.reload({waitUntil:'domcontentloaded'});
 await second.waitForSelector('.admin-shell');
 assert.equal(await second.getByLabel('公告栏标题',{exact:true}).inputValue(),'标签页 B 的修改');
 await second.close();
 await page.setViewportSize({width:800,height:1000});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),true,'平板布局不能横向溢出');
 await page.setViewportSize({width:390,height:844});
 await page.getByRole('button',{name:'打开导航',exact:true}).click();
 await page.locator('.admin-sidebar.open .admin-account-main').waitFor();
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),true,'手机布局不能横向溢出');
 await page.locator('.admin-account-main').click();
 await page.getByRole('button',{name:'退出登录',exact:true}).click();
 await page.waitForSelector('.admin-login');
 assert.equal(loggedIn,false,'退出应调用服务端路由');
 assert.deepEqual(errors,[]);
 // Browser storage denial must not stop session setup or repository loading.
 loggedIn=true;
 const blocked=await browser.newPage();
 const blockedErrors=[];
 blocked.on('pageerror',error=>{blockedErrors.push(error.message);console.error(error.stack);});
 await blocked.addInitScript(()=>{
  Object.defineProperty(window,'localStorage',{get(){const error=new Error('Storage disabled');error.name='SecurityError';throw error;}});
  Object.defineProperty(window,'sessionStorage',{get(){const error=new Error('Storage disabled');error.name='SecurityError';throw error;}});
 });
 await blocked.route('**/api/writing/**',mockApi);
 await blocked.goto(origin+'/admin/',{waitUntil:'domcontentloaded'});
 await blocked.waitForSelector('.admin-shell');
 await blocked.locator('.admin-sidebar nav button').filter({hasText:'公告管理'}).click();
 await blocked.getByLabel('公告栏标题',{exact:true}).waitFor();
 assert.deepEqual(blockedErrors,[]);
 await blocked.close();
 console.log('Admin state browser tests passed: original version, notebook navigation, conflict recovery, independent tabs, denied storage and logout.');
}finally{await browser.close();}
